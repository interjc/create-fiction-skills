import {
  mkdirSync, mkdtempSync, readdirSync, readFileSync, renameSync, rmdirSync, unlinkSync, writeFileSync,
} from 'node:fs';
import path from 'node:path';
import { namedExport } from './javascript.mjs';
import { compare, isObject, splitLines, stat } from './repo.mjs';

const skillName = /^fiction-[a-z0-9]+(?:-[a-z0-9]+)*$/;
const entryName = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const marker = source => `// GENERATED by tools/sync-shared.mjs. Edit ${source} instead.`;
const wrapper = entry => Buffer.from([
  '#!/usr/bin/env node',
  marker(`shared/lib/${entry}.mjs`),
  `import { main } from './lib/${entry}.mjs';`,
  'process.exitCode = await main(process.argv.slice(2));',
  '',
].join('\n'));

function assertDir(root, file, optional = false) {
  const info = stat(path.join(root, file));
  if (!info && optional) return false;
  if (!info?.isDirectory()) throw new Error(`需要普通目录：${file}`);
  return true;
}

function read(root, file, optional = false) {
  const absolute = path.join(root, file);
  const info = stat(absolute);
  if (!info && optional) return undefined;
  if (!info?.isFile()) throw new Error(`需要普通文件：${file}`);
  return readFileSync(absolute);
}

function manifest(root) {
  const file = 'shared/manifest.json';
  const text = read(root, file).toString('utf8');
  let parsed;
  try {
    parsed = JSON.parse(text);
  } catch (error) {
    throw new Error(`${file}：${error.message}`);
  }
  if (!isObject(parsed) || Object.keys(parsed).length !== 1 || !isObject(parsed.skills)) {
    throw new Error(`${file}：清单必须包含 skills 映射`);
  }
  for (const [skill, entries] of Object.entries(parsed.skills)) {
    if (!skillName.test(skill) || skill.length > 64 || !Array.isArray(entries) ||
        entries.some(entry => typeof entry !== 'string' || !entryName.test(entry)) ||
        new Set(entries).size !== entries.length) {
      throw new Error(`${file}：无效的 skill 或入口列表：${skill}`);
    }
  }
  return parsed.skills;
}

function sourceTree(root, dir) {
  const tree = new Map();
  for (const child of readdirSync(path.join(root, dir), { withFileTypes: true })) {
    const relative = `${dir}/${child.name}`;
    tree.set(child.name, child.isDirectory() ? sourceTree(root, relative) : read(root, relative));
  }
  return tree;
}

function localModule(specifier) {
  if (specifier.startsWith('./') || specifier.startsWith('../')) {
    const pathname = specifier.split(/[?#]/u, 1)[0];
    if (/%(?:2f|5c)/i.test(pathname)) return;
    try {
      return path.posix.normalize(decodeURIComponent(pathname));
    } catch {
      return undefined;
    }
  }
}

function hasExport(lib, file, name, visiting = new Set()) {
  const key = JSON.stringify([file, name]);
  if (visiting.has(key) || !lib.has(file)) return false;
  const { explicit, from, imported, stars } = namedExport(lib.get(file).toString('utf8'), name);
  if (explicit && from === undefined) return true;
  visiting.add(key);
  try {
    if (explicit) return hasExport(lib, localModule(from), imported, visiting);
    const providers = new Set(stars.map(localModule));
    return [...providers].filter(next => hasExport(lib, next, name, visiting)).length === 1;
  } finally {
    visiting.delete(key);
  }
}

function replaceFile(target, bytes) {
  // Replace rather than modify the existing inode (which may have hard links).
  const tmp = mkdtempSync(path.join(path.dirname(target), '.sync-shared-'));
  const file = path.join(tmp, 'file');
  try {
    writeFileSync(file, bytes, { mode: stat(target).mode & 0o777 });
    renameSync(file, target);
  } finally {
    if (stat(file)) unlinkSync(file);
    rmdirSync(tmp);
  }
}

function hasMarker(bytes, owner) {
  const [first, second] = splitLines(bytes.toString('utf8'));
  return first === owner || (first.startsWith('#!') && second === owner);
}

export function syncShared(root, { check = false, skill } = {}) {
  assertDir(root, 'shared');
  const skills = manifest(root);
  if (skill !== undefined && !Object.hasOwn(skills, skill)) throw new Error(`清单没有此 skill：${skill}`);

  assertDir(root, 'shared/lib');
  const lib = new Map();
  for (const child of readdirSync(path.join(root, 'shared/lib'), { withFileTypes: true })) {
    if (child.name.endsWith('.mjs') && !child.isDirectory()) {
      lib.set(child.name, read(root, `shared/lib/${child.name}`));
    }
  }
  for (const entry of new Set(Object.values(skills).flat())) {
    if (!lib.has(`${entry}.mjs`)) throw new Error(`入口模块不存在：shared/lib/${entry}.mjs`);
    if (!hasExport(lib, `${entry}.mjs`, 'main')) throw new Error(`入口模块缺少 main 导出：shared/lib/${entry}.mjs`);
  }
  const tests = assertDir(root, 'shared/tests', true);
  const fixtures = tests && assertDir(root, 'shared/tests/fixtures-shared', true)
    ? sourceTree(root, 'shared/tests/fixtures-shared') : undefined;
  const changes = [];
  const operations = [];
  const actions = check ? ['missing', 'drift', 'stale'] : ['create', 'update', 'delete'];

  for (const name of skill === undefined ? Object.keys(skills).sort(compare) : [skill]) {
    const scripts = `skills/${name}/scripts`;
    const testDir = `${scripts}/tests`;
    const entries = skills[name];
    for (const dir of [`skills/${name}`, scripts, testDir]) assertDir(root, dir, true);
    const record = (kind, file, operation) => {
      changes.push({ skill: name, action: actions[kind], file });
      operations.push(operation);
    };
    const makeDir = file => () => mkdirSync(path.join(root, file), { recursive: true });

    function copy(file, bytes, owner) {
      const target = path.join(root, file);
      const current = stat(target);
      if (!current) {
        record(0, file, () => {
          makeDir(path.posix.dirname(file))();
          writeFileSync(target, bytes, { flag: 'wx' });
        });
        return;
      }
      if (!current.isFile()) {
        if (!check) throw new Error(`拒绝覆盖非普通文件：${file}`);
        record(1, file);
        return;
      }
      const old = readFileSync(target);
      if (old.equals(bytes)) return;
      if (!check && owner && !hasMarker(old, owner)) {
        throw new Error(`拒绝覆盖无法确认归属的文件：${file}`);
      }
      record(1, file, () => replaceFile(target, bytes));
    }

    function remove(file) {
      const target = path.join(root, file);
      if (stat(target).isDirectory()) {
        const children = readdirSync(target);
        for (const child of children) remove(`${file}/${child}`);
        if (children.length) operations.push(() => rmdirSync(target));
        else record(2, file, () => rmdirSync(target));
      } else {
        record(2, file, () => unlinkSync(target));
      }
    }

    function mirror(dir, tree) {
      const absolute = path.join(root, dir);
      const current = stat(absolute);
      if (!tree) {
        if (current) remove(dir);
        return;
      }
      if (current && !current.isDirectory()) {
        if (!check) throw new Error(`拒绝覆盖非目录：${dir}`);
        record(1, dir);
        return;
      }
      if (!current && !tree.size) record(0, dir, makeDir(dir));
      for (const [child, bytes] of tree) {
        if (bytes instanceof Map) mirror(`${dir}/${child}`, bytes);
        else copy(`${dir}/${child}`, bytes);
      }
      if (current) for (const child of readdirSync(absolute)) {
        if (!tree.has(child)) remove(`${dir}/${child}`);
      }
    }

    mirror(`${scripts}/lib`, lib);
    for (const entry of entries) {
      copy(`${scripts}/${entry}.mjs`, wrapper(entry), marker(`shared/lib/${entry}.mjs`));
      const test = `${entry}.test.mjs`;
      const source = `shared/tests/${test}`;
      const bytes = tests && read(root, source, true);
      // The exact marker is opt-in for an otherwise byte-for-byte test copy.
      if (bytes) copy(`${testDir}/${test}`, bytes, marker(source));
    }
    mirror(`${testDir}/fixtures-shared`, entries.length ? fixtures : undefined);
  }

  // Preflight every selected skill before changing any of them.
  if (!check) for (const operation of operations) operation();
  changes.sort((a, b) => compare(a.file, b.file) || compare(a.action, b.action));
  return { ok: !check || changes.length === 0, mode: check ? 'check' : 'write', changes };
}
