test('format preflight refuses conflicting non-files in both modes without deleting outside the owned directory', t => {
  const root = fixture(t);
  fixtureFormats(root);
  const dir = `${notes}/references/formats`;
  put(root, 'author.md', '手稿');
  mkdirSync(path.join(root, dir), { recursive: true });
  const target = path.join(root, 'author.md');
  const args = ['--skill', 'fiction-notes'];
  symlinkSync(target, path.join(root, `${dir}/whole.md`));
  assert.deepEqual(sync(root, [...args, '--check'], 2), []);
  assert.deepEqual(sync(root, args, 2), []);
  assert.equal(get(root, 'author.md'), '手稿');
  assert.equal(exists(root, scripts), false);
  unlinkSync(path.join(root, `${dir}/whole.md`));
  symlinkSync(target, path.join(root, `${dir}/stale.md`));
  sync(root, args, 0);
  assert.equal(exists(root, `${dir}/stale.md`), false);
  assert.equal(get(root, 'author.md'), '手稿');
});

