import assert from 'node:assert/strict';
import { existsSync, mkdirSync, readFileSync, symlinkSync, unlinkSync } from 'node:fs';
import path from 'node:path';
import { test } from 'node:test';
import { exactKeys, fixture, get, json, put, run, scripts } from './fixture.mjs';

const wrapper = `${scripts}/record.mjs`;
const testCopy = `${scripts}/tests/record.test.mjs`;
const testSource = 'shared/tests/record.test.mjs';
const fixtureDir = `${scripts}/tests/fixtures-shared`;
const fixtureSource = 'shared/tests/fixtures-shared';
const manifest = 'shared/manifest.json';
const other = 'skills/fiction-margin/scripts';

function sync(root, args, status) {
  const result = json(root, 'sync-shared', args, status);
  exactKeys(result, 'tool spec_version root ok mode changes');
  assert.equal(result.mode, args.includes('--check') ? 'check' : 'write');
  for (const change of result.changes) exactKeys(change, 'skill action file');
  return result.changes;
}

const exists = (root, file) => existsSync(path.join(root, file));
const read = (root, file) => readFileSync(path.join(root, file));

test('sync creates exact wrappers and byte-for-byte lib, test and recursive fixture copies', t => {
  const root = fixture(t);
  const input = Buffer.from("// 注释\r\nexport const paper = '邮戳';\r\n");
  put(root, 'shared/lib/paper.mjs', input);
  put(root, 'shared/lib/ignore.txt', 'late addition');
  put(root, 'shared/lib/sub/ignore.mjs', 'export const ignored = 1;\n');
  put(root, `${fixtureSource}/postcards/data.bin`, Buffer.from([0, 255, 10, 3]));
  mkdirSync(path.join(root, fixtureSource, 'empty'));
  const missing = sync(root, ['--check'], 1);
  assert.equal(exists(root, scripts), false);
  assert.ok(missing.every(item => item.action === 'missing'));
  const created = sync(root, [], 0);
  assert.deepEqual(created, missing.map(item => ({ ...item, action: 'create' })));
  assert.deepEqual(read(root, `${scripts}/lib/paper.mjs`), input);
  assert.deepEqual(read(root, `${other}/lib/paper.mjs`), input);
  assert.equal(get(root, wrapper), [
    '#!/usr/bin/env node',
    '// GENERATED by tools/sync-shared.mjs. Edit shared/lib/record.mjs instead.',
    "import { main } from './lib/record.mjs';",
    'process.exitCode = await main(process.argv.slice(2));',
    '',
  ].join('\n'));
  assert.deepEqual(read(root, testCopy), read(root, testSource));
  for (const file of ['postcards/front.txt', 'postcards/data.bin']) {
    assert.deepEqual(read(root, `${fixtureDir}/${file}`), read(root, `${fixtureSource}/${file}`));
  }
  assert.equal(exists(root, `${fixtureDir}/empty`), true);
  for (const file of ['lib/ignore.txt', 'lib/sub', `${other}/tests`]) assert.equal(exists(root, file.startsWith(other) ? file : `${scripts}/${file}`), false);
  assert.deepEqual(sync(root, ['--check'], 0), []);
  assert.deepEqual(sync(root, [], 0), []);
});

test('sync --skill restricts changes and can create a missing skill directory', t => {
  const root = fixture(t);
  put(root, manifest, JSON.stringify({ skills: { 'fiction-new': ['record'], 'fiction-notes': ['record'] } }));
  const changes = sync(root, ['--skill', 'fiction-new', '--root', root], 0);
  assert.ok(changes.length && changes.every(change => change.skill === 'fiction-new'));
  assert.equal(exists(root, 'skills/fiction-new/scripts/record.mjs'), true);
  assert.equal(exists(root, 'skills/fiction-new/SKILL.md'), false);
  assert.equal(exists(root, scripts), false);
  assert.deepEqual(sync(root, ['--skill', 'fiction-new', '--check'], 0), []);
  sync(root, ['--skill', 'fiction-unknown'], 2);
});

test('sync plans updates and stale deletions without writing, then repairs only owned paths', t => {
  const root = fixture(t);
  sync(root, [], 0);
  const skewedWrapper = get(root, wrapper) + '// outdated\n';
  put(root, wrapper, skewedWrapper);
  put(root, testSource, `${get(root, testSource)}// 扉页\n`);
  put(root, 'shared/lib/paper.mjs', 'export const paper = "插页";\r\n');
  put(root, `${fixtureSource}/postcards/front.txt`, '渡口送来一叠小纸片。\n');
  put(root, `${fixtureDir}/obsolete/deeper/entry.txt`, 'stale');
  put(root, `${scripts}/lib/debris/old.data`, 'stale');
  put(root, `${scripts}/author.mjs`, 'export const kept = true;');
  put(root, `${scripts}/tests/author.test.mjs`, 'export const kept = true;');
  const check = sync(root, ['--check', '--skill', 'fiction-notes'], 1);
  assert.deepEqual(check.map(x => [x.action, x.file]), [
    ['stale', `${scripts}/lib/debris/old.data`],
    ['drift', `${scripts}/lib/paper.mjs`],
    ['drift', wrapper],
    ['stale', `${fixtureDir}/obsolete/deeper/entry.txt`],
    ['drift', `${fixtureDir}/postcards/front.txt`],
    ['drift', testCopy],
  ]);
  assert.equal(get(root, wrapper), skewedWrapper);
  assert.equal(exists(root, `${scripts}/lib/debris/old.data`), true);
  const written = sync(root, ['--skill', 'fiction-notes'], 0);
  assert.deepEqual(written, check.map(item => ({ ...item, action: item.action === 'drift' ? 'update' : 'delete' })));
  assert.deepEqual(read(root, testCopy), read(root, testSource));
  assert.deepEqual(read(root, `${fixtureDir}/postcards/front.txt`), read(root, `${fixtureSource}/postcards/front.txt`));
  assert.ok(!exists(root, `${fixtureDir}/obsolete`) && !exists(root, `${scripts}/lib/debris`));
  assert.ok(exists(root, `${scripts}/author.mjs`) && exists(root, `${scripts}/tests/author.test.mjs`));
  assert.deepEqual(sync(root, ['--check', '--skill', 'fiction-notes'], 0), []);
  assert.deepEqual(sync(root, ['--check'], 1).map(x => x.skill), ['fiction-margin']);
});

test('sync refuses unmarked wrapper or test collisions before any write', t => {
  const root = fixture(t);
  const personal = 'export const draft = "保留";\n';
  for (const file of [wrapper, testCopy]) {
    put(root, file, personal);
    const changes = sync(root, ['--check'], 1);
    assert.ok(changes.some(change => change.action === 'drift' && change.file === file));
    const result = run(root, 'sync-shared', []);
    assert.equal(result.status, 2);
    assert.equal(result.stdout, '');
    assert.match(result.stderr, /拒绝覆盖/);
    assert.deepEqual(sync(root, [], 2), []);
    assert.equal(get(root, file), personal);
    assert.equal(exists(root, other), false);
    assert.equal(exists(root, `${scripts}/lib`), false);
    unlinkSync(path.join(root, file));
  }
  sync(root, [], 0);
});

test('sync accepts an identical unmarked test but never removes files in mixed-ownership directories', t => {
  const root = fixture(t);
  put(root, testSource, get(root, testSource).split('\n').slice(1).join('\n'));
  put(root, testCopy, get(root, testSource));
  sync(root, [], 0);
  put(root, testSource, `${get(root, testSource)}// 本次修订\n`);
  sync(root, ['--check'], 1);
  sync(root, [], 2);
  unlinkSync(path.join(root, testSource));
  put(root, manifest, JSON.stringify({ skills: { 'fiction-notes': [] } }));
  const changes = sync(root, [], 0);
  assert.ok(changes.length && changes.every(item => item.action === 'delete' && item.file.startsWith(fixtureDir)));
  assert.equal(exists(root, wrapper), true);
  assert.equal(exists(root, testCopy), true);
  assert.deepEqual(sync(root, ['--check'], 0), []);
});

test('sync validates manifest structure, entry existence and real named main exports without execution', t => {
  const root = fixture(t);
  for (const invalid of [
    '{',
    '{"skills":[]}',
    '{"skills":{"../elsewhere":["record"]}}',
    '{"skills":{"fiction-notes":["../record"]}}',
    '{"skills":{"fiction-notes":["record","record"]}}',
    '{"skills":{"fiction-notes":["missing"]}}',
    '{"skills":{"fiction-notes":"record"}}',
  ]) {
    put(root, manifest, invalid);
    sync(root, ['--check'], 2);
    sync(root, [], 2);
    assert.equal(exists(root, scripts), false);
  }
  put(root, manifest, '{"skills":{"fiction-notes":["record"]}}');
  const entry = 'shared/lib/record.mjs';
  for (const missing of [
    'export default function main() {}',
    'const main = () => 0;\nexport {main as otherwise};',
    'const text = "export function main() {}";\n// export {main};',
    'export const other = /export function main/;',
    'export const other = 0\nconst unrelated = 1, main = () => 0;\n',
    'export const { main: renamed } = item;\n',
    "export { main } from './paper.mjs';",
  ]) {
    put(root, entry, missing);
    sync(root, [], 2);
  }
  put(root, entry, "export const impl = () => 0;\nexport { impl as main };\nthrow new Error('do not execute');\n");
  sync(root, [], 0);
  put(root, 'shared/lib/implementation.mjs', 'export const { entry: main } = { entry: () => 0 };\n');
  put(root, entry, "export { main } from './implementation.mjs';\n");
  sync(root, [], 0);
  put(root, entry, "export * from './implementation.mjs';\n");
  sync(root, [], 0);
  assert.deepEqual(sync(root, ['--check'], 0), []);
});

test('sync never follows a destination symlink and only unlinks stale symlinks in owned directories', t => {
  const root = fixture(t);
  sync(root, [], 0);
  put(root, 'outside.md', '不可改动');
  const outside = path.join(root, 'outside.md');
  const destination = path.join(root, scripts, 'lib/paper.mjs');
  unlinkSync(destination);
  symlinkSync(outside, destination);
  sync(root, ['--check'], 1);
  sync(root, [], 2);
  assert.equal(get(root, 'outside.md'), '不可改动');
  unlinkSync(destination);
  symlinkSync(outside, path.join(root, scripts, 'lib/stale-link'));
  const changes = sync(root, [], 0);
  assert.ok(changes.some(item => item.action === 'delete' && item.file.endsWith('/stale-link')));
  assert.equal(get(root, 'outside.md'), '不可改动');
});
