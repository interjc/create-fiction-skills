test('formats-only --skill, owned stale directories, and missing/drift/stale have check/write parity', t => {
  const root = fixture(t);
  fixtureFormats(root);
  const card = 'skills/fiction-card/references/formats/lead.md';
  const cardArgs = ['--skill', 'fiction-card'];
  assert.deepEqual(sync(root, [...cardArgs, '--check'], 1), [{ skill: 'fiction-card', action: 'missing', file: card }]);
  assert.equal(exists(root, card), false);
  sync(root, cardArgs, 0);
  assert.equal(exists(root, 'skills/fiction-card/scripts'), false);
  assert.equal(exists(root, scripts), false);
  sync(root, [], 0);

  const dir = `${notes}/references/formats`;
  const stale = `${dir}/old/note.txt`;
  const margin = 'skills/fiction-margin/references/formats';
  const orphan = 'skills/fiction-unused/references/formats';
  put(root, `${dir}/lead.md`, '旧开场，无生成标记');
  unlinkSync(path.join(root, `${dir}/note.md`));
  put(root, stale, '旧纸片');
  mkdirSync(path.join(root, margin), { recursive: true });
  put(root, `${orphan}/left.md`, '旧目录');
  const keep = `${notes}/references/nested/cards.md`;
  const manual = get(root, keep);
  const delta = sync(root, ['--check'], 1);
  assert.deepEqual(delta.map(({ action, file }) => [action, file]), [
    ['stale', margin], ['drift', `${dir}/lead.md`], ['missing', `${dir}/note.md`],
    ['stale', stale], ['stale', `${orphan}/left.md`],
  ]);
  assert.equal(get(root, `${dir}/lead.md`), '旧开场，无生成标记');
  assert.equal(exists(root, `${dir}/note.md`), false);
  assert.equal(exists(root, `${orphan}/left.md`), true);
  const action = { stale: 'delete', drift: 'update', missing: 'create' };
  assert.deepEqual(sync(root, [], 0), delta.map(change => ({ ...change, action: action[change.action] })));
  for (const gone of [margin, orphan, `${dir}/old`]) assert.equal(exists(root, gone), false);
  assert.equal(get(root, keep), manual);
  assert.deepEqual(sync(root, ['--check'], 0), []);
});

